export function buildCopyPrompt(a: Analysis): string {
  const data = buildPromptData(a);
  const header = `# 마음결 · ${koreanDate(a.takenOn)}의 나`;
  return [
    PROMPT_INTRO,
    "",
    "<result>",
    JSON.stringify(data),
    "</result>",
    "",
    "<about_test>",
    ...ABOUT_TEST.map((l) => `- ${l}`),
    "</about_test>",
    "",
    "<rules>",
    ...PROMPT_RULES.map((r, i) => `${i + 1}. ${r}`),
    "</rules>",
    "",
    "<answer_format>",
    `맨 위에 아래 제목 한 줄을 그대로 쓰고, 이어서 항목마다 "## 번호. 제목" 줄로 시작해 주세요.`,
    header,
    ...PROMPT_SECTIONS.map((s, i) => `## ${i + 1}. ${s.title}: ${s.ask}`),
    "</answer_format>",
  ].join("\n");
}
